"""Reclamations sent by students and processed by administrators. Stored in MongoDB.

One document per reclamation in the `reclamations` collection. Its status history is embedded
(an array of sub-documents), so a reclamation is always read and written as a single document,
which MongoDB updates atomically.

`author_sub` is the verified Keycloak UUID. Nullable legacy `author_id` values remain for
inspection only and never grant access. There are no cross-database foreign keys.
Business rules (references, workflow, who may change what) live in services.py.
"""

import re

from django.conf import settings
from django.core.exceptions import ValidationError
from django.core.validators import MaxValueValidator, MinLengthValidator, MinValueValidator
from django.db import models
from django_mongodb_backend.fields import EmbeddedModelArrayField, ObjectIdAutoField
from django_mongodb_backend.models import EmbeddedModel

SUBJECT_MIN_LENGTH, SUBJECT_MAX_LENGTH = 5, 150
DESCRIPTION_MIN_LENGTH, DESCRIPTION_MAX_LENGTH = 20, 5000
MODULE_MAX_LENGTH = 100
COURSE_ID_MAX = 2**31 - 1  # Course ids are PostgreSQL serials (Course Service)
ADMIN_RESPONSE_MAX_LENGTH = 5000
COMMENT_MAX_LENGTH = 1000
USERNAME_MAX_LENGTH = 150  # same as django.contrib.auth

ACADEMIC_YEAR_PATTERN = re.compile(r"(\d{4})-(\d{4})")


class Category(models.TextChoices):
    GRADE = "grade", "Grade"
    EXAM = "exam", "Exam"
    ABSENCE = "absence", "Absence"
    REGISTRATION = "registration", "Registration"
    INTERNSHIP = "internship", "Internship"
    ADMINISTRATIVE = "administrative", "Administrative"
    OTHER = "other", "Other"


class Status(models.TextChoices):
    NEW = "new", "New"
    IN_PROGRESS = "in_progress", "In progress"
    RESOLVED = "resolved", "Resolved"
    REJECTED = "rejected", "Rejected"


class Priority(models.TextChoices):
    LOW = "low", "Low"
    NORMAL = "normal", "Normal"
    HIGH = "high", "High"


def validate_academic_year(value):
    """YYYY-YYYY with consecutive years, e.g. 2026-2027."""
    match = ACADEMIC_YEAR_PATTERN.fullmatch(value or "")
    if not match or int(match[2]) != int(match[1]) + 1:
        raise ValidationError("Use the format YYYY-YYYY with consecutive years, e.g. 2026-2027.",
                              code="invalid_academic_year")


def default_academic_year():
    return settings.RAG["ACADEMIC_YEAR"]  # read at call time, like rag.config.cfg()


class HistoryEntry(EmbeddedModel):
    """One status change. The first entry (from_status = null) records the creation."""

    from_status = models.CharField(max_length=20, choices=Status.choices, null=True, blank=True)
    to_status = models.CharField(max_length=20, choices=Status.choices)
    by_user_id = models.IntegerField(null=True, blank=True)
    by_sub = models.CharField(max_length=36, null=True, blank=True, editable=False)
    by_username = models.CharField(max_length=USERNAME_MAX_LENGTH)
    comment = models.TextField(max_length=COMMENT_MAX_LENGTH, blank=True, default="")
    at = models.DateTimeField()


class Reclamation(models.Model):
    id = ObjectIdAutoField(primary_key=True)
    # REC-<year>-<00001>: generated by services.next_reference(), never by the client
    reference = models.CharField(max_length=20, unique=True, editable=False)
    author_id = models.IntegerField(editable=False, null=True, blank=True)
    author_sub = models.CharField(max_length=36, null=True, blank=True, editable=False)
    author_username = models.CharField(max_length=USERNAME_MAX_LENGTH, editable=False)
    category = models.CharField(max_length=20, choices=Category.choices)
    subject = models.CharField(max_length=SUBJECT_MAX_LENGTH,
                               validators=[MinLengthValidator(SUBJECT_MIN_LENGTH)])
    description = models.TextField(max_length=DESCRIPTION_MAX_LENGTH,
                                   validators=[MinLengthValidator(DESCRIPTION_MIN_LENGTH)])
    module = models.CharField(max_length=MODULE_MAX_LENGTH, blank=True, default="")
    # Optional id of a Course Service course, checked with GET /courses/{id} at creation (no
    # cross-service foreign key). Set at creation only. Missing in older documents = null.
    course_id = models.PositiveIntegerField(null=True, blank=True,
                                            validators=[MinValueValidator(1), MaxValueValidator(COURSE_ID_MAX)])
    academic_year = models.CharField(max_length=9, default=default_academic_year,
                                     validators=[validate_academic_year])
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.NEW, editable=False)
    priority = models.CharField(max_length=10, choices=Priority.choices, default=Priority.NORMAL,
                                editable=False)
    admin_response = models.TextField(max_length=ADMIN_RESPONSE_MAX_LENGTH, blank=True, default="",
                                      editable=False)
    history = EmbeddedModelArrayField(HistoryEntry, default=list, editable=False)
    created_at = models.DateTimeField(editable=False)
    updated_at = models.DateTimeField(editable=False)
    closed_at = models.DateTimeField(null=True, blank=True, editable=False)  # set on resolved/rejected

    class Meta:
        db_table = "reclamations"
        # The id breaks ties: MongoDB stores datetimes with millisecond precision only
        ordering = ["-created_at", "-id"]
        indexes = [
            # "my reclamations, newest first"
            models.Index(fields=["author_id", "-created_at"], name="reclamation_author_recent"),
            models.Index(fields=["author_sub", "-created_at"], name="reclamation_sub_recent"),
            models.Index(fields=["status"], name="reclamation_status"),
            models.Index(fields=["category"], name="reclamation_category"),
        ]

    def __str__(self):
        return f"{self.reference} {self.subject}"
